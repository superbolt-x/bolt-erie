        {#  erie_type now follows the PRODUCT, not the source-code prefix.

            `source ~* 'B'` was only ever a proxy for "this lead is Basement", used because
            the daily file carried Roofing only. It is wrong in both directions, and both
            are measurable in the raw file since 2025-01-01:
              - 217 Roof leads carry a B-prefixed source (BIL2 73, BSMR 67, BSM5 28, ...)
                and were being labelled Basement. That is the entire 251 sf_leads currently
                sitting under erie_type='Basement' in blended — Roofing leads with no
                Basement spend to match.
              - 459 Basement leads carry a non-B source (SM3, IL2, IL5, SMD, ...) because
                a Roofing campaign generated a Basement sale. Those were dropped entirely.

            `prod` is authoritative, so use it. NULL prod (~20k rows, no product recorded)
            keeps the old proxy rather than silently defaulting to Roofing.

            NOTE the deliberate consequence: a Basement lead generated by a Roofing campaign
            is now erie_type='Basement' while the spend that produced it is
            erie_type='Roofing'. That is correct for product reporting and it is what the
            old prod filter already implied, but it means those leads have no matching
            Basement spend. Measured at 14 of 968 Google leads (1.4%) for May-Aug 2026 —
            immaterial, but it is why Basement CPL should be read at channel grain, not
            campaign grain, until the volume is understood. #}
        CASE WHEN prod = 'Basement Waterproofing' THEN 'Basement'
            WHEN prod = 'Roof' THEN 'Roofing'
            WHEN prod IS NULL AND source ~* 'B' AND source != 'BNA' THEN 'Basement'
            ELSE 'Roofing'
        END as erie_type,
        CASE WHEN source IN ('SMR','SM1','SM4','BSM4','IL3','BIL3','SM3','BSMR','BSM1','SM5','BSM5') THEN 'National'
            WHEN source IN ('SM','SMO','SM2','BSM','BSM2') THEN 'Local'
            WHEN source = 'RYT' THEN 'Retargeting'
            ELSE 'Other'
        END as market,
        CASE WHEN source IN ('SM2','SM4','SM1','SM','BSM','BSM2','BSM1') 
                OR (utm_source ~* 'facebook' AND utm_campaign !~* 'warm') THEN 'Prospecting'
            WHEN source IN ('SMR','SMO','BSMR')
                OR (utm_source ~* 'facebook' AND utm_campaign ~* 'warm') THEN 'Retargeting'
            WHEN source IN ('SMD','BSMD') OR (utm_source ~* 'google' AND utm_campaign ~* 'discovery') OR (utm_source ~* 'google' AND utm_campaign ~* 'demand gen') THEN 'Demand Gen'
            WHEN source IN ('PMX','BPMX','PMX2') OR (utm_source ~* 'google' AND COALESCE(advertising_channel_type, nm_channel_type) = 'PERFORMANCE_MAX') THEN 'Performance Max'
            WHEN source IN ('IL2','BIL2','IL3','BIL3','IL5','BIL5') OR (utm_source ~* 'google' AND COALESCE(advertising_channel_type, nm_channel_type) = 'SEARCH')THEN 'Search'
			WHEN source IN ('BNA') THEN 'Audience'
        END as campaign_type,
        {{ region_bucket(['COALESCE(bg_campaign_name, nm_campaign_name)::VARCHAR', 'utm_campaign']) }} as region_bucket,
        {{ service_type_bucket(['COALESCE(gb_ad_group_name, utm_ad_group_name)::VARCHAR', 'utm_term']) }} as service_type,

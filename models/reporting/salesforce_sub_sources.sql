    FROM (SELECT *, COALESCE(utm_campaign_id::VARCHAR,utm_campaign) as utm_campaign_id_adj
            FROM {{ source('reporting','salesforce_performance') }}) s
    LEFT JOIN (SELECT campaign_id::VARCHAR as campaign_id, campaign_name as bg_campaign_name, advertising_channel_type
            FROM {{ ref('googleads_campaigns') }}
            UNION ALL
            SELECT campaign_id::VARCHAR as campaign_id, campaign_name as bg_campaign_name, NULL as advertising_channel_type
            FROM {{ ref('bingads_campaigns') }}
            UNION ALL
            SELECT campaign_id::VARCHAR as campaign_id, campaign_name as bg_campaign_name, NULL as advertising_channel_type
            FROM {{ ref('facebook_campaigns') }}
            ) bg ON s.utm_campaign_id_adj = bg.campaign_id
    {#  NAME-BASED CAMPAIGN JOIN — the Basement path.

        The id join above resolves Roofing, which carries utm_campaign_id. Basement does
        not: utm_campaign_id is populated on 0 of 14,230 facebook rows and 591 of 8,777
        google rows. Basement carries the campaign NAME instead, so it is joined on a
        normalised name key (see macros/normalize_campaign_name.sql for why raw names do
        not match).

        Aggregated to one row per key before joining, so a name that exists on more than one
        platform cannot fan out the lead rows. The id join still wins wherever it resolves —
        this is a COALESCE fallback, so Roofing behaviour is unchanged.  #}
    LEFT JOIN (SELECT {{ normalize_campaign_name('campaign_name') }} as name_key,
                      MAX(campaign_name) as nm_campaign_name,
                      MAX(advertising_channel_type) as nm_channel_type
            FROM (SELECT campaign_name, advertising_channel_type FROM {{ ref('googleads_campaigns') }}
                  UNION ALL
                  SELECT campaign_name, NULL as advertising_channel_type FROM {{ ref('bingads_campaigns') }}
                  UNION ALL
                  SELECT campaign_name, NULL as advertising_channel_type FROM {{ ref('facebook_campaigns') }})
            WHERE campaign_name IS NOT NULL AND campaign_name <> ''
            GROUP BY 1
            ) nm ON {{ normalize_campaign_name('s.utm_campaign') }} = nm.name_key
                AND bg.campaign_id IS NULL
    LEFT JOIN (SELECT ad_group_id::VARCHAR as ad_group_id, ad_group_name as gb_ad_group_name
            FROM {{ ref('googleads_ad_groups') }}
            UNION ALL
            SELECT ad_group_id::VARCHAR as ad_group_id, ad_group_name as gb_ad_group_name
            FROM {{ ref('bingads_ad_groups') }}
            UNION ALL
            SELECT asset_group_id::VARCHAR as ad_group_id, asset_group_name as gb_ad_group_name
            FROM {{ ref('googleads_asset_groups') }}
            ) gb ON s.utm_term = gb.ad_group_id
    WHERE date >= '2022-12-01'

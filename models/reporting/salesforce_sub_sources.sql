        CASE WHEN source IN ('PMX','BPMX','IL2','SMD','BIL2','BSMD') OR utm_source ~* 'google' THEN COALESCE(bg_campaign_name, nm_campaign_name)::VARCHAR
            WHEN source IN ('IL3','BIL3','BNA','PMX2') OR utm_source ~* 'bing' THEN COALESCE(bg_campaign_name, nm_campaign_name)::VARCHAR
            WHEN utm_campaign_id = 6930690664241 THEN 'Soc - Meta - Roofing - Prospecting - National - Florida Regional - Lead - CBO (Lifetime) Campaign'
	  		WHEN utm_campaign_id = 6931185343441 THEN 'Soc - Meta - Roofing - Prospecting - National - Great Lakes and East Great Lakes Regional - Instant Form - Lifetime'
	  	  	WHEN utm_campaign_id = 6930683609841 THEN 'Soc - Meta - Roofing - Prospecting - National - Northeast Regional - Lead - CBO (Lifetime) Campaign'
            {#  Meta path: prefer the current platform name resolved by campaign_id (bg,
                extended below with facebook_campaigns) over the raw utm_campaign text, which
                is hardcoded in the Instant Form and goes stale whenever a campaign is
                duplicated/renamed. utm_campaign_id itself is reliably populated on Meta
                (unlike Basement), so this is a straight id join, no name-normalization needed. #}
            ELSE COALESCE(bg_campaign_name, utm_campaign)::VARCHAR
        END as utm_campaign,
        CASE WHEN source IN ('PMX','BPMX','IL2','SMD','BIL2','BSMD') OR utm_source ~* 'google' THEN COALESCE(gb_ad_group_name, utm_ad_group_name)::VARCHAR
            WHEN source IN ('IL3','BIL3') OR (utm_source ~* 'bing' AND source NOT IN ('BNA','PMX2')) THEN COALESCE(gb_ad_group_name, utm_ad_group_name)::VARCHAR
			WHEN utm_source ~* 'bing' AND source IN ('BNA','PMX2') THEN NULL
            ELSE utm_term::VARCHAR
        END as utm_term,
        utm_content::VARCHAR,
        {#  Roofing and Basement put different things in utm_term, so the two slots have to
            be filled from different columns to line the grains up.

              Roofing  utm_term = the numeric ad_group_id, resolved to a name by the gb join
                       above; utm_keyword = the keyword (Bing only).
              Basement utm_term = the SEARCH TERM text — verified never a numeric id
                       (0 of 2,457 Google rows, 1 of 353 Bing, Jan-Aug 2026) — while the ad
                       group arrives separately as utm_ad_group_name (534 Google / 76 Bing)
                       and utm_keyword is barely wired up yet (127 Google / 50 Bing).

            So the ad-group slot takes utm_ad_group_name (done above) and the search term
            falls through to utm_keyword here, which is the closest Roofing equivalent that
            exists. Meta has neither: utm_term is the ad set name and the creative is in
            utm_content, which already lines up with Roofing.  #}
        CASE WHEN utm_source ~* 'bing' AND source NOT IN ('BNA','PMX2') THEN COALESCE(utm_keyword, utm_term)
            WHEN utm_source ~* 'google' AND gb_ad_group_name IS NULL THEN COALESCE(utm_keyword, utm_term)
            ELSE NULL
        END AS utm_keyword,
        '' as utm_match_type,
